// The skift.v1 services: three faces over one contract. GraphService reads
// and mutates the graph, WorkService hands out and manages leases, and
// EventService serves the change stream. docs/domain-model.md is the
// rationale; docs/architecture.md says where each is served.
//
// Node references. Wherever a request names a node it does so with a single
// string in one of four forms: "#7" for a node in the request's project,
// "slug#7" for a node in another project of the same organization,
// "org/slug#7" fully qualified, or an alias declared by a create_node
